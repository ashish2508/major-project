import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { format } from 'prettier';
import { digest } from '../src/lib/digest';
import type { DetectionConfig, Method } from '../src/lib/detection/detector';
import type { PanMetrics } from '../src/lib/evaluation/pan';
import { reportDirectory as directory } from './research-paths';

const methods = ['lexical', 'semantic', 'hybrid'] as const;
const names = { lexical: 'TF-IDF', semantic: 'MiniLM', hybrid: 'Hybrid' };
type TestResult = {
  config: DetectionConfig;
  metrics: PanMetrics;
  perType: Record<string, { metrics: PanMetrics | null }>;
  cleanQueries: number;
  cleanQueriesWithAlerts: number;
};

const [benchmark, frozen, config, split, predictions] = await Promise.all(
  [
    'benchmark-results.json',
    'frozen-parameters.json',
    'experiment-config.json',
    'split-manifest.json',
    'test-predictions.json',
  ].map((file) => readFile(`${directory}/${file}`, 'utf8')),
);
const result = JSON.parse(benchmark) as {
  runCompletedAt: string;
  corpusFingerprint: string;
  splitManifestSha256: string;
  experimentConfigSha256: string;
  validation: Record<Method, PanMetrics>;
  test: Record<Method, TestResult>;
  timing: { totalWallSeconds: number; peakRssBytes: number };
};
const experiment = JSON.parse(config);
const parameters = JSON.parse(frozen);
const detections = JSON.parse(predictions);
assert.equal(result.corpusFingerprint, experiment.corpusFingerprint);
assert.equal(result.splitManifestSha256, digest(split));
assert.equal(result.splitManifestSha256, parameters.splitManifestSha256);
assert.equal(result.experimentConfigSha256, digest(JSON.stringify(experiment)));
assert.equal(result.experimentConfigSha256, parameters.experimentConfigSha256);
assert.equal(parameters.selectionPartition, 'validation');
for (const method of methods) {
  assert.deepEqual(result.test[method].config, parameters.methods[method]);
  assert.equal(detections[method].length, result.test[method].metrics.detections);
}

const rows = methods.map((method) => {
  const { config, metrics, cleanQueries, cleanQueriesWithAlerts } = result.test[method];
  const { precision, recall, f1, granularity, plagdet } = metrics;
  return [
    names[method],
    config.threshold,
    config.alpha,
    result.validation[method].plagdet.toFixed(4),
    ...[precision, recall, f1, granularity, plagdet].map((score) => score.toFixed(4)),
    `${metrics.missedCases}/${metrics.cases}`,
    metrics.falsePositiveDetections,
    `${cleanQueriesWithAlerts}/${cleanQueries}`,
  ];
});
const strata = ['artificial/none', 'artificial/low', 'artificial/high', 'simulated'].map((type) => [
  type,
  ...methods.map((method) => {
    const metrics = result.test[method].perType[type]?.metrics;
    return metrics ? `${metrics.detectedCases}/${metrics.cases}` : '—';
  }),
]);
const markdown = `# PAN-PC-11 benchmark summary

Generated by \`bun run report:research\` from the saved comparison completed at ${result.runCompletedAt}. This is a bounded English external-detection experiment with a reduced candidate collection.

| Method | Threshold | Lexical weight | Validation PlagDet | Test precision | Test recall | Test F1 | Test granularity | Test PlagDet | Missed cases | Unmatched detections | Clean queries flagged |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.map((row) => `| ${row.join(' | ')} |`).join('\n')}

## Held-out cases with a matching detection

| Construction | TF-IDF | MiniLM | Hybrid |
| --- | --- | --- | --- |
${strata.map((row) => `| ${row.join(' | ')} |`).join('\n')}

A case counts as matched only when a detection identifies the same document pair and overlaps both annotated spans. Clean-query alerts use the unannotated test queries as their denominator. The single simulated case is illustrative.

The complete recorded run took ${result.timing.totalWallSeconds.toFixed(2)} seconds and used ${(result.timing.peakRssBytes / 2 ** 20).toFixed(1)} MiB peak process RSS. This is shared benchmark execution, including embedding generation or cache access, and cannot be attributed to any one detector.

See the [frozen parameters](frozen-parameters.json), [validation search](validation-search.json), [full results](benchmark-results.json), [predictions](test-predictions.json), and [experiment configuration](experiment-config.json).
`;
const path = `${directory}/benchmark-summary.md`;
await writeFile(path, await format(markdown, { parser: 'markdown' }));
console.log(`Wrote ${path}`);
